import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync,spawnSync} from 'node:child_process';
const root='auditoria/p2-20261024-01';
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const original=JSON.parse(fs.readFileSync(`${root}/hashes-p1.json`,'utf8'));
for(const file of ['index.html','tools/check_site.mjs','tools/validate_files.py','AUDITORIA-VISUAL-FINI.md','RELATORIO-P1-FINI.md'])assert.equal(hash(file),original[file],file);
for(const file of fs.readdirSync('assets/images'))assert.equal(hash(`assets/images/${file}`),hash(`${root}/backup-p1/assets/images/${file}`),file);
const motion=JSON.parse(fs.readFileSync(`${root}/motion-approved-build/results.json`,'utf8'));
assert.equal(motion.failure,null);assert.deepEqual(motion.errors,[]);
for(const mode of ['delivery','focus'])assert.match(fs.readFileSync(`${root}/tests-${mode}/existing-tests.log`,'utf8'),/Exit: 0/);
let log='';for(const [cmd,args] of [['python',['-B','tools/validate_files.py']],['node',['--check','js/script.js']],['git',['diff','--check']]])log+=`> ${cmd} ${args.join(' ')}\n${execFileSync(cmd,args,{encoding:'utf8'})}\n`;
fs.writeFileSync(`${root}/checks-finais.log`,log,{flag:'wx'});
let patch='';for(const file of ['css/style.css','js/script.js'])patch+=spawnSync('git',['diff','--no-index',`${root}/backup-p1/${file}`,file],{encoding:'utf8'}).stdout;
fs.writeFileSync(`${root}/p1-to-p2.patch`,patch,{flag:'wx'});
fs.writeFileSync(`${root}/git-final.txt`,execFileSync('git',['status','--short'],{encoding:'utf8'}),{flag:'wx'});
const manifest={changedSinceP1:['css/style.css','js/script.js'],unchangedHTML:true,unchangedAssets:21,clips:motion.clips.length,frames:motion.clips.reduce((n,c)=>n+c.frames,0),checks:motion.checks,hashes:{css:hash('css/style.css'),js:hash('js/script.js')}};
fs.writeFileSync(`${root}/manifesto-final.json`,JSON.stringify(manifest,null,2),{flag:'wx'});
console.log(JSON.stringify(manifest,null,2));
